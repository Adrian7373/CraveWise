"""Phase E: per-100 g nutrition from USDA FoodData Central (SR Legacy) and grams per recipe line.

The app only multiplies: every recipe line ships `grams` (null = not covered) and every ingredient
ships `nutrition` per 100 g (null = no FDC match). All unit and portion logic lives here.

Curation:
- curation/nutrition_pins.json  HAND-EDITED. ingredient id -> fdcId, {"fdcId": n, "note": "proxy: ..."},
  or null (no sensible match). Pins always win over the matcher.
- curation/nutrition.json  GENERATED by `build.py nutrition`: id -> {fdcId, desc, by: hand|auto, score}.
- curation/portions.json   ingredient id -> {unit: grams per 1 unit, "each": g, "ml": g per ml}.
  Hand values beat FDC portions, which beat the generic DEFAULTS below.
"""
from __future__ import annotations

import csv
import io
import json
import re
import zipfile

from .ingredients import _singular, fold
from .measures import is_negligible
from .paths import CURATION, RAW_FDC

SR_ZIP = RAW_FDC / "sr_legacy.zip"
SR_URL = "https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip"
SR_INDEX = RAW_FDC / "sr_index.json"
NUTRITION = CURATION / "nutrition.json"
PINS = CURATION / "nutrition_pins.json"
PORTIONS = CURATION / "portions.json"

# FDC nutrient ids -> our keys (per 100 g; sodium in mg, the rest in g / kcal).
NUTRIENTS = {"1008": "kcal", "1003": "protein", "1005": "carbs", "1004": "fat",
             "1079": "fiber", "2000": "sugar", "1093": "sodium"}
KEYS = ("kcal", "protein", "carbs", "fat", "fiber", "sugar", "sodium")

# Same constants as the app's ShoppingQuantities.
MASS_G = {"g": 1.0, "kg": 1000.0, "oz": 28.3495, "lb": 453.592}
VOLUME_ML = {"ml": 1.0, "l": 1000.0, "tsp": 4.92892, "tbsp": 14.7868, "cup": 236.588, "fl_oz": 29.5735}
TINY_ML = {"pinch": 0.3, "dash": 0.6, "splash": 5.0}

# Generic grams per unit when neither portions.json nor FDC knows better.
DEFAULTS = {"can": 400.0, "jar": 340.0, "bottle": 330.0, "handful": 30.0, "knob": 15.0, "sprig": 1.0,
            "leaf": 0.5, "bunch": 30.0, "fillet": 150.0, "stick": 113.0, "stalk": 40.0, "slice": 30.0,
            "clove": 3.0, "cm": 4.0}

_PORTION_KEYS = [
    (r"cups?\b", "cup"), (r"(tablespoons?|tbsps?)\b", "tbsp"), (r"(teaspoons?|tsps?)\b", "tsp"),
    (r"fl oz\b", "fl_oz"), (r"(liters?|litres?)\b", "l"), (r"cloves?\b", "clove"), (r"slices?\b", "slice"),
    (r"stalks?\b", "stalk"), (r"(leaves|leaf)\b", "leaf"), (r"sprigs?\b", "sprig"), (r"heads?\b", "head"),
    (r"fillets?\b", "fillet"), (r"sheets?\b", "sheet"), (r"sticks?\b", "stick"), (r"pieces?\b", "piece"),
]
# A portion named after a whole item: "medium", "whole", or the food's own noun ("pepper", "Potato
# medium", "thigh without skin", "link").
_EACH_WORDS = {"medium", "large", "small", "extra", "jumbo", "whole", "each", "fruit", "item", "link",
               "bulb", "patty", "bun", "roll", "breast", "thigh", "drumstick", "wing", "leg", "fillet"}
# When nothing is "each", a bare count most likely means one of these ("2 garlic" = cloves).
_EACH_FALLBACK = ("head", "clove", "stalk", "slice", "leaf", "piece")


def _size_rank(mod: str) -> float:
    """Prefer medium portions, then plain, then large/small."""
    if "medium" in mod:
        return 0
    if "small" in mod or "large" in mod or "jumbo" in mod:
        return 2
    return 1


def classify_portion(mod: str, desc_tokens: set[str]) -> str | None:
    m = mod.strip().lower()
    for pattern, key in _PORTION_KEYS:
        if re.match(pattern, m):
            return key
    words = re.findall(r"[a-z]+", m)
    if words and (words[0] in _EACH_WORDS or _singular(words[0]) in desc_tokens):
        return "each"
    return None


# ---- loading FDC ------------------------------------------------------------------------------
def load_sr() -> dict[str, dict]:
    """fdc_id -> {desc, cat, n: {kcal..}, p: [[modifier, g per 1]]}. Cached as sr_index.json."""
    if SR_INDEX.exists():
        return json.loads(SR_INDEX.read_text(encoding="utf-8"))
    if not SR_ZIP.exists():
        raise SystemExit(f"Missing {SR_ZIP}. Download {SR_URL} there (see CLAUDE.md, Seed pipeline).")
    z = zipfile.ZipFile(SR_ZIP)
    prefix = next(n for n in z.namelist() if n.endswith("food.csv")).rsplit("/", 1)[0] + "/"

    def rows(name):
        return csv.DictReader(io.TextIOWrapper(z.open(prefix + name), encoding="utf-8"))

    cats = {r["id"]: r["description"] for r in rows("food_category.csv")}
    foods = {r["fdc_id"]: {"desc": r["description"], "cat": cats.get(r["food_category_id"], ""), "n": {}, "p": []}
             for r in rows("food.csv")}
    for r in rows("food_nutrient.csv"):
        key = NUTRIENTS.get(r["nutrient_id"])
        if key and r["fdc_id"] in foods and r["amount"]:
            foods[r["fdc_id"]]["n"][key] = float(r["amount"])
    for r in rows("food_portion.csv"):
        f = foods.get(r["fdc_id"])
        if not f:
            continue
        try:
            amount, grams = float(r["amount"] or 1), float(r["gram_weight"])
        except ValueError:
            continue
        mod = (r["modifier"] or r["portion_description"] or "").strip()
        if amount > 0 and mod:
            f["p"].append([mod, round(grams / amount, 3)])
    SR_INDEX.write_text(json.dumps(foods), encoding="utf-8")
    return foods


# ---- matching ---------------------------------------------------------------------------------
_NEUTRAL = {"raw", "fresh", "whole", "plain", "regular", "all", "purpose", "enriched", "bleached",
            "unenriched", "commercial", "ns", "as", "to", "form", "and", "or", "with", "of", "in", "the",
            "solid", "solids", "liquid", "unprepared", "prepared", "mature", "seed", "dry", "dried",
            "ground", "uncooked", "unsweetened", "salted", "table", "granulated", "includes", "usda",
            "commodity", "pure", "without", "salt", "added", "unheated", "flesh", "skin", "only", "lean",
            "fat", "separable", "trimmed", "inch", "choice", "select", "grade", "all", "u", "s", "us"}
_BAD = {"babyfood", "infant", "imitation", "fast", "restaurant", "frozen", "canned", "cooked", "boiled",
        "fried", "roasted", "baked", "braised", "dehydrated", "low", "reduced", "free", "lowfat", "nonfat",
        "light", "diet", "substitute", "flavored", "mix", "candied", "sweetened", "toddler", "formula"}
_BAD_CATS = {"Baby Foods", "Fast Foods", "Restaurant Foods", "Meals, Entrees, and Side Dishes"}


def _tokens(text: str) -> list[str]:
    return [_singular(w) for w in re.findall(r"[a-z]+", fold(text))]


_BRAND = re.compile(r"\b[A-Z]{2,}\b|\b(Pillsbury|Kraft|Campbell|Kellogg|Heinz|McCormick)\b")


class _Prepared:
    """Foods tokenized once, indexed by token, so matching 700 names stays fast."""

    def __init__(self, foods: dict[str, dict]):
        self.foods = foods
        self.meta: dict[str, tuple[set, set, float]] = {}
        self.index: dict[str, list[str]] = {}
        for fid, f in foods.items():
            desc = f["desc"]
            head = set(_tokens(desc.split(",")[0]))
            toks = set(_tokens(desc))
            base = 0.0
            if f["cat"] in _BAD_CATS:
                base -= 4
            if _BRAND.search(desc):
                base -= 3
            if "kcal" not in f["n"]:
                base -= 10
            if "raw" in toks:
                base += 0.8
            self.meta[fid] = (head, toks, base)
            for t in toks:
                self.index.setdefault(t, []).append(fid)


def _score(want: list[str], head: set, toks: set, base: float) -> float:
    s = base
    for w in want:
        s += 3 if w in head else 1.5 if w in toks else -2.5
    if want[-1] not in toks:            # the head noun must appear somewhere
        s -= 6
    extra = toks - set(want)
    s -= sum(1.2 if t in _BAD else 0 if t in _NEUTRAL else 0.4 for t in extra)
    return s


def score(name: str, food: dict) -> float:
    """Single-food score (tests and debugging)."""
    p = _Prepared({"x": food})
    want = _tokens(name)
    return _score(want, *p.meta["x"]) if want else -99


def best_match(name: str, prepared: _Prepared) -> tuple[str | None, float]:
    want = _tokens(name)
    if not want:
        return None, -99.0
    best, best_s = None, -99.0
    for fid in prepared.index.get(want[-1], []):
        s = _score(want, *prepared.meta[fid])
        if s > best_s or (s == best_s and best and len(prepared.foods[fid]["desc"]) < len(prepared.foods[best]["desc"])):
            best, best_s = fid, s
    return best, best_s


def search(query: str, foods: dict[str, dict], limit: int = 8) -> list[tuple[str, str]]:
    """Foods whose description contains every query word (singularized), shortest first."""
    want = set(_tokens(query))
    hits = [(fid, f["desc"]) for fid, f in foods.items() if want <= set(_tokens(f["desc"])) and "kcal" in f["n"]]
    return sorted(hits, key=lambda h: len(h[1]))[:limit]


ACCEPT = 2.0


def match_all(items: list[dict], foods: dict[str, dict]) -> dict:
    """Pins first, the matcher for everything else. Returns the new nutrition.json."""
    pins = json.loads(PINS.read_text(encoding="utf-8")) if PINS.exists() else {}
    pins.pop("_comment", None)
    known = {it["id"] for it in items}
    for stray in sorted(set(pins) - known):
        print(f"  warning: nutrition_pins.json pins unknown ingredient {stray!r}")
    out = {}
    prepared = _Prepared(foods)
    for it in items:
        iid = it["id"]
        if iid in pins:
            pin = pins[iid]
            fid = pin.get("fdcId") if isinstance(pin, dict) else pin
            if fid is not None and str(fid) not in foods:
                raise SystemExit(f"nutrition_pins.json: {iid} -> fdcId {fid} is not in SR Legacy")
            out[iid] = {"fdcId": fid, "desc": foods[str(fid)]["desc"] if fid else "", "by": "hand",
                        **({"note": pin["note"]} if isinstance(pin, dict) and pin.get("note") else {})}
            continue
        fid, s = best_match(it["name"], prepared)
        ok = fid is not None and s >= ACCEPT
        out[iid] = {"fdcId": int(fid) if ok else None, "desc": foods[fid]["desc"] if fid else "",
                    "by": "auto", "score": round(s, 2)}
    return out


# ---- per-ingredient facts -------------------------------------------------------------------
def facts(iid: str, nut: dict, foods: dict, hand_portions: dict) -> tuple[dict | None, dict]:
    """(nutrition per 100 g or None, portions {unit: g, 'each': g, 'ml': g/ml})."""
    pin = nut.get(iid) or {}
    fid = pin.get("fdcId")
    food = foods.get(str(fid)) if fid else None
    nutrition = None
    if food and "kcal" in food["n"]:
        nutrition = {"fdcId": int(fid), **{k: round(food["n"].get(k, 0.0), 2) for k in KEYS}}
    portions: dict[str, float] = {}
    if food:
        toks = set(_tokens(food["desc"]))
        best: dict[str, tuple[float, float]] = {}
        for mod, g in food["p"]:
            key = classify_portion(mod, toks)
            if key and (key not in best or _size_rank(mod.lower()) < best[key][0]):
                best[key] = (_size_rank(mod.lower()), g)
        p = {k: v[1] for k, v in best.items()}
        portions.update({k: v for k, v in p.items() if k in VOLUME_ML or k in DEFAULTS or k in ("sheet", "head", "piece", "each")})
        if "each" not in portions:
            for k in _EACH_FALLBACK:
                if k in p:
                    portions["each"] = p[k]
                    break
        for vol in ("cup", "tbsp", "tsp", "fl_oz", "l"):
            if vol in p:
                portions["ml"] = round(p[vol] / VOLUME_ML[vol], 4)
                break
    portions.update(hand_portions.get(iid, {}))
    return nutrition, portions


_PACK = re.compile(r"(\d+(?:\.\d+)?)\s*(g|kg|ml|l|oz)\b", re.I)


def line_grams(amount, amount_max, unit, note, raw_measure, portions: dict) -> tuple[float | None, str]:
    """Grams for one recipe line at the recipe's own servings, plus a short reason."""
    if amount is None:
        return (0.0, "negligible") if is_negligible(raw_measure) else (None, "unparsed")
    amt = (amount + amount_max) / 2 if amount_max else amount
    if unit in MASS_G:
        return amt * MASS_G[unit], "mass"
    if unit in TINY_ML:
        return amt * TINY_ML[unit] * portions.get("ml", 1.0), "tiny"
    if unit in VOLUME_ML:
        if unit in portions:
            return amt * portions[unit], "fdc volume"
        if "ml" in portions:
            return amt * VOLUME_ML[unit] * portions["ml"], "density"
        return None, "no density"
    if unit in ("can", "jar", "bottle", "packet", None) and note and (m := _PACK.search(note)):
        n, u = float(m.group(1)), m.group(2).lower()
        g = n * (MASS_G.get(u) or VOLUME_ML.get(u, 1.0) * portions.get("ml", 1.0))
        return amt * g, "pack size"
    if unit is None:
        if "whole" in portions and (amt <= 1 or "whole" in (note or "").lower()):
            return amt * portions["whole"], "whole"
        return (amt * portions["each"], "each") if "each" in portions else (None, "no each weight")
    if unit in portions:
        return amt * portions[unit], "portion"
    if unit in DEFAULTS:
        return amt * DEFAULTS[unit], "default"
    return None, f"no weight for {unit}"


# Deep-frying: only part of the oil ends up in the food.
FRY_RE = re.compile(r"\b(deep[- ]?fr\w*|fry|fries|fried|frying|hot oil)\b", re.I)
FRY_ABSORBED = 0.15
FRY_MIN_GRAMS = 100


def frying_oil(grams: float, nutrition: dict | None, instructions: str) -> bool:
    """A big amount of an almost-pure fat in a recipe that fries is frying oil."""
    return bool(nutrition and nutrition.get("fat", 0) >= 90 and grams > FRY_MIN_GRAMS and FRY_RE.search(instructions or ""))


def load_curation() -> tuple[dict, dict]:
    nut = json.loads(NUTRITION.read_text(encoding="utf-8")) if NUTRITION.exists() else {}
    por = json.loads(PORTIONS.read_text(encoding="utf-8")) if PORTIONS.exists() else {}
    por.pop("_comment", None)
    return nut, por
