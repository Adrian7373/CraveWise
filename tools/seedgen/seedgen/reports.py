"""Markdown review sheets and audit reports (committed under curation/ and out/)."""
from __future__ import annotations

from collections import Counter, defaultdict

from .ingredients import IngredientTable


def _facts(i: dict) -> str:
    parts = [f"allergens: **{', '.join(i['allergens']) or 'none'}**",
             f"contains: {', '.join(i['contains']) or 'none'}"]
    if i.get("protein"):
        parts.append(f"protein: {i['protein']}")
    if i.get("isPantryStaple"):
        parts.append("staple")
    return " · ".join(parts)


def ingredients_review(table: IngredientTable, uses: Counter) -> str:
    pending = [i for i in table.items if not i.get("reviewed")]
    out = [
        "# Ingredient review",
        "",
        "Generated by `python tools/seedgen/build.py ingredients`. **Edit `ingredients.json`, not this file.**",
        "",
        "For each ingredient: check `aisle`, `allergens` (EU 14), `contains`, `protein`, `isPantryStaple` and the",
        "merged spellings (`synonyms`), fix them in `ingredients.json`, then set `\"reviewed\": true`.",
        "Values here were proposed by keyword rules and are **not trusted**: the build fails while any",
        "ingredient a recipe uses still has `reviewed: false`. Brand-dependent items list only the",
        "allergens inherent to the food; add more if you want to be stricter.",
        "",
        f"**{len(pending)} of {len(table.items)} awaiting review.** Sorted by aisle, then by how many recipe lines use them.",
        "",
    ]
    added = [(i, i["proposal"]["addedSynonyms"]) for i in table.items
             if i.get("proposal", {}).get("addedSynonyms")]
    if added:
        out += ["## New spellings merged into existing ingredients", ""]
        out += [f"- `{i['id']}` ← {', '.join(s)}" for i, s in added]
        out.append("")
    by_aisle: dict[str, list[dict]] = defaultdict(list)
    for i in pending:
        by_aisle[i["aisle"]].append(i)
    for aisle in sorted(by_aisle):
        out += [f"## {aisle} ({len(by_aisle[aisle])})", ""]
        for i in sorted(by_aisle[aisle], key=lambda i: (-uses.get(i["id"], 0), i["id"])):
            syn = f" · also: {', '.join(i['synonyms'])}" if i["synonyms"] else ""
            note = f" · ⚠ {i['notes']}" if i.get("notes") else ""
            out.append(f"- [ ] `{i['id']}` **{i['name']}** ({uses.get(i['id'], 0)} uses) · {_facts(i)}{syn}{note}")
        out.append("")
    return "\n".join(out)
