# Method words that imply an allergen. TheMealDB ingredient lists sometimes omit things the steps
# use (e.g. "tuna" in sushi). Flagged for review; NEVER used as a source of allergens.
STEP_ALLERGEN_WORDS = {
    "gluten": r"\bflour|\bbread|breadcrumb|\bpasta\b|noodle|spaghetti|couscous|pastry|tortilla|pitta|\bpita\b|wheat|barley|semolina|\bbeer\b",
    "milk": r"\bbutter\b(?! beans?)|\bmilk\b(?<!coconut milk)|\bcream\b(?<!coconut cream)|cheese|parmesan|yog(h)?urt|\bghee\b|cr[eè]me|mozzarella|\bfeta\b",
    "eggs": r"\beggs?\b(?!plant)|\byolks?\b|mayonnaise|meringue",
    "fish": r"\bfish\b|anchov|salmon|\btuna\b|\bcod\b|fish sauce|worcestershire",
    "crustaceans": r"prawn|shrimp|\bcrab|lobster|crayfish",
    "molluscs": r"mussel|\bclams?\b|oyster(?! mushroom)|squid|octopus|scallop",
    "peanuts": r"peanut|groundnut",
    "tree_nuts": r"almond|walnut|cashew|pecan|pistachio|hazelnut|macadamia|pine nut",
    "soy": r"\bsoy\b|soya|\btofu\b|\bmiso\b|edamame",
    "sesame": r"sesame|tahini",
    "mustard": r"mustard",
    "celery": r"celery|celeriac",
    "sulphites": r"\bwine\b|vinegar|sherry",
}
CHILLI = re.compile(r"chilli|chili|chile|cayenne|jalapeno|scotch_bonnet|habanero|gochujang|sriracha|hot_sauce|"
                    r"harissa|curry_paste|pul_biber|birds_eye|doubanjiang|piri|jerk|wasabi|madras|curry_powder|"
                    r"sichuan|peppercorn|horseradish|chilli_bean")


def step_allergen_gaps(r: Recipe, allergens: set[str]) -> list[str]:
    text = " ".join(r.steps).lower()
    gaps = []
    for allergen, pattern in STEP_ALLERGEN_WORDS.items():
        if allergen not in allergens and (m := re.search(pattern, text)):
            gaps.append(f"{allergen}? (method says '{m.group(0)}')")
    return gaps


def _fmt(v) -> str:
    return ", ".join(v) if isinstance(v, list) else str(v)


def provenance(merged: dict) -> dict:
    return {rid: prov for rid, (_, prov, _) in sorted(merged.items())}


def review_sheet(ids: list[str], recipes: dict[str, Recipe], merged: dict, overrides: dict, by_id: dict) -> str:
    out = ["# Top-50 review", "",
           "Generated by `python tools/seedgen/build.py review`. **Edit `curation/overrides.json`, not this file.**", "",
           "For each recipe: check the tags, write any fix into `overrides.json` under the recipe id",
           "(`flavor` can be partial, e.g. `{\"spicy\": 2}`), and set `\"reviewed\": true` there.",
           "Sources: `override` (yours) · `rule` (confident rule) · `ai` (Claude) · `rule-low` (weak rule, nothing better).",
           "Allergens/diets/proteins are a PREVIEW derived from the ingredient table (fix those in `ingredients.json`).", ""]
    done = sum(1 for i in ids if overrides.get(i, {}).get("reviewed"))
    out += [f"**{done} of {len(ids)} reviewed.**", ""]
    for rid in ids:
        r = recipes[rid]
        values, prov, missing = merged[rid]
        ings = [by_id[l.ingredient_id] for l in r.lines if l.ingredient_id in by_id]
        allergens, diets, proteins = diet.derive(ings)
        unreviewed = sorted({i["id"] for i in ings if not i.get("reviewed")})
        tick = "x" if overrides.get(rid, {}).get("reviewed") else " "
        out += [f"## [{tick}] {r.title} · `{rid}`", "",
                f"{values.get('cuisine', '?')} · {', '.join(values.get('mealTypes', []))} · TheMealDB {r.category} · "
                f"{len(r.steps)} steps · [source]({r.source_url})", "",
                "**Ingredients:** " + "; ".join(f"{l.raw_measure} {by_id.get(l.ingredient_id, {}).get('name', l.raw_name)}".strip()
                                                 for l in r.lines), "",
                f"**Derived (preview):** allergens {', '.join(sorted(allergens)) or 'none'} · diets {', '.join(sorted(diets)) or 'none'} · "
                f"proteins {', '.join(sorted(proteins)) or 'none'}"]
        gaps = step_allergen_gaps(r, allergens)
        if gaps:
            out.append(f"**⚠ Method mentions allergens missing from the ingredients:** {'; '.join(gaps)}")
        if unreviewed:
            out.append(f"**Unreviewed ingredients:** {', '.join(unreviewed)}")
        out += ["", "| field | value | source | reason |", "|---|---|---|---|"]
        for f in FIELDS:
            if f in prov:
                out.append(f"| {f} | {_fmt(values[f])} | {prov[f]['source']} | {prov[f]['reason']} |")
            else:
                out.append(f"| {f} | **MISSING** | | |")
        out.append("")
    return "\n".join(out)


def audit(recipes: list[Recipe], merged: dict, by_id: dict, vocab, cuisines: set[str], ai_errors: list[str]) -> str:
    sections: dict[str, list[str]] = {
        "Vocabulary violations": [], "Missing fields": [], "Recipes with zero parsed amounts": [],
        "Ingredients missing or with an unknown aisle": [], "Spicy ≥ 4 with no chilli-type ingredient": [],
        "Total time over 6 hours": [], "Method mentions allergens missing from the ingredients": [],
        "Step splits that need a look": [], "Unmapped ingredient lines": [],
    }
    sections["Vocabulary violations"] += [f"AI answer: {e}" for e in ai_errors]
    sources = Counter()
    for r in recipes:
        values, prov, missing = merged[r.id]
        for f, v in values.items():
            if (err := validate_value(f, v, vocab, cuisines)):
                sections["Vocabulary violations"].append(f"`{r.id}` {r.title}: {err} ({prov[f]['source']})")
        if missing:
            sections["Missing fields"].append(f"`{r.id}` {r.title}: {', '.join(missing)}")
        for p in prov.values():
            sources[p["source"]] += 1
        if not any(l.amount is not None for l in r.lines):
            sections["Recipes with zero parsed amounts"].append(f"`{r.id}` {r.title}")
        ids = [l.ingredient_id for l in r.lines if l.ingredient_id]
        if values.get("flavor.spicy", 0) >= 4 and not any(CHILLI.search(i) for i in ids):
            sections["Spicy ≥ 4 with no chilli-type ingredient"].append(f"`{r.id}` {r.title} (spicy {values['flavor.spicy']}, {prov['flavor.spicy']['source']})")
        total = values.get("prepMinutes", 0) + values.get("cookMinutes", 0)
        if total > 360:
            sections["Total time over 6 hours"].append(f"`{r.id}` {r.title}: {values['prepMinutes']} prep + {values['cookMinutes']} cook")
        ings = [by_id[i] for i in ids if i in by_id]
        gaps = step_allergen_gaps(r, diet.derive(ings)[0])
        if gaps:
            sections["Method mentions allergens missing from the ingredients"].append(f"`{r.id}` {r.title}: {'; '.join(gaps)}")
        if not r.steps or len(r.steps) > 25 or any(len(s) > 600 for s in r.steps):
            sections["Step splits that need a look"].append(f"`{r.id}` {r.title}: {len(r.steps)} steps")
        for l in r.lines:
            if not l.ingredient_id:
                sections["Unmapped ingredient lines"].append(f"`{r.id}` {l.raw_name}")
    used = {l.ingredient_id for r in recipes for l in r.lines if l.ingredient_id}
    for iid in sorted(used):
        ing = by_id.get(iid, {})
        if ing.get("aisle") not in vocab.aisles:
            sections["Ingredients missing or with an unknown aisle"].append(f"`{iid}` aisle={ing.get('aisle')!r}")
    unreviewed = sum(1 for iid in used if not by_id.get(iid, {}).get("reviewed"))
    out = ["# Seed audit", "", "Generated by `python tools/seedgen/build.py review`.", "",
           f"- {len(recipes)} recipes, {len(used)} ingredients used, **{unreviewed} ingredients awaiting allergen review**",
           f"- tag sources across all fields: {dict(sources)}",
           f"- cuisine 'International': {sum(1 for v, _, _ in merged.values() if v.get('cuisine') == 'International')}", ""]
    for title, items in sections.items():
        out += [f"## {title} ({len(items)})", ""]
        out += [f"- {i}" for i in items[:300]] or ["None."]
        if len(items) > 300:
            out.append(f"- … and {len(items) - 300} more")
        out.append("")
    return "\n".join(out)


def write_json(path, data) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
